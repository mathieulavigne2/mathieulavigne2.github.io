"""Download and self-host the site's webfonts.

Fetches Source Serif 4 and Source Sans 3 from Google Fonts, keeps only the
latin and latin-ext subsets (latin-ext carries the accented characters the
French side needs), stores the woff2 files under assets/fonts/, and writes
html/_fonts.scss pointing at them.

Self-hosting rather than linking fonts.googleapis.com means no third-party
request on page load - no CDN dependency, nothing for a visitor's browser to
report to Google, and no render-blocking round trip to another origin.

Both families are licensed under the SIL Open Font License 1.1, which permits
redistribution. See assets/fonts/LICENSE.txt.

Run from the repo root, only when the font selection changes:

    python tools/fetch-fonts.py
"""

import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets" / "fonts"
# A Sass partial, not a .css file, so theme.scss can @import it and have Sass
# inline the rules rather than emitting a second stylesheet request.
SCSS_OUT = ROOT / "html" / "_fonts.scss"

# A browser UA is required, otherwise Google serves legacy ttf instead of woff2.
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")

# Request only the weights actually used, and deliberately NOT the `opsz`
# axis: including it ships the full variable font and takes Source Serif 4
# from 21 KB to 119 KB per subset for no visible benefit at our sizes.
API = (
    "https://fonts.googleapis.com/css2"
    "?family=Source+Serif+4:wght@600"
    "&family=Source+Sans+3:ital,wght@0,400;0,600;1,400"
    "&display=swap"
)

# Identify the two subsets we keep by a distinctive codepoint in their range.
WANTED = {"U+0000-00FF": "latin", "U+0100-02BA": "latin-ext"}

# Kept in sync with the note at the top of the generated partial.
HEADER = """\
// GENERATED by tools/fetch-fonts.py - do not edit.
// Self-hosted Source Serif 4 + Source Sans 3 (SIL OFL 1.1).
// Imported by html/theme.scss so Sass inlines the rules.
//
// URLs are ABSOLUTE (/assets/...) on purpose. Quarto resolves relative CSS
// dependency paths against the project root but does NOT rewrite them to be
// relative to the compiled stylesheet's own location, so a relative path
// either fails to resolve at build time or 404s at run time. The site is
// served from a domain root, so an absolute path is correct both in the
// published site and in local preview.
//
// assets/fonts/ is force-copied via `project: resources:` in _quarto.yml,
// because Quarto cannot see references made from inside compiled CSS.

"""

LICENSE_NOTE = """\
Source Serif 4 and Source Sans 3
Copyright 2014-2023 Adobe (http://www.adobe.com/), with Reserved Font Names
'Source'. Licensed under the SIL Open Font License, Version 1.1.

Full licence: https://openfontlicense.org/

These files are redistributed here to avoid a third-party request to
fonts.googleapis.com on every page load. Regenerate with
tools/fetch-fonts.py.
"""


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = resp.read()
    return data if binary else data.decode("utf-8")


def main():
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    css = fetch(API)

    kept, downloaded = [], 0

    for block in re.findall(r"@font-face\s*\{[^}]*\}", css):
        rng = re.search(r"unicode-range:\s*([^;]+);", block)
        if not rng:
            continue
        subset = next((v for k, v in WANTED.items() if k in rng.group(1)), None)
        if subset is None:
            continue

        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        weight = re.search(r"font-weight:\s*([\d\s]+);", block).group(1).strip()
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
        # Style must be in the filename, or the italic face silently
        # overwrites the roman at the same weight.
        style = "italic" if "font-style: italic" in block else "normal"

        slug = family.lower().replace(" ", "-")
        name = f"{slug}-{weight.replace(' ', '-')}-{style}-{subset}.woff2"
        (FONT_DIR / name).write_bytes(fetch(url, binary=True))
        downloaded += 1

        kept.append(block.replace(url, f"/assets/fonts/{name}"))
        print(f"  {name}  ({(FONT_DIR / name).stat().st_size / 1024:.0f} KB)")

    SCSS_OUT.write_text(HEADER + "\n".join(kept) + "\n", encoding="utf-8")
    (FONT_DIR / "LICENSE.txt").write_text(LICENSE_NOTE, encoding="utf-8")

    total = sum(f.stat().st_size for f in FONT_DIR.glob("*.woff2")) / 1024
    print(f"\n{downloaded} font files, {total:.0f} KB total -> {SCSS_OUT.name}")


if __name__ == "__main__":
    main()
